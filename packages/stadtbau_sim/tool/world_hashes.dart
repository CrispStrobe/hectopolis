// Writes test/world_hashes.g.dart: the hash of a few simulated worlds, as the
// VM computes them. test/hash_test.dart compares against it in the VM (so the
// file must be current) and in Chrome (so a browser must agree with the VM).
// The values follow the model, so a parameter change means running this:
//
//     dart run tool/world_hashes.dart
import 'dart:io';

import 'package:stadtbau_sim/stadtbau_sim.dart';

/// The worlds hash_test simulates, by name.
Map<String, int> simulatedWorldHashes() => {
  for (final id in ['village', 'tuebingen'])
    id: (Level.byId(id)!.start()..apply(const AdvanceTick(13))).state.hash(),
  'sandbox':
      (Simulation.sandbox(width: 8, height: 8)
            ..apply(const PlaceTile(2, 2, TileType.housingHigh))
            ..apply(const AdvanceTick(5)))
          .state
          .hash(),
};

void main() {
  final hashes = simulatedWorldHashes();
  final out = StringBuffer()
    ..writeln('// SPDX-License-Identifier: AGPL-3.0-or-later')
    ..writeln('// GENERATED by tool/world_hashes.dart -- do not edit.')
    ..writeln('const simulatedWorldHashesInVm = <String, int>{');
  for (final MapEntry(:key, :value) in hashes.entries) {
    out.writeln("  '$key': $value,");
  }
  out.writeln('};');
  File('test/world_hashes.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote test/world_hashes.g.dart: $hashes');
}
